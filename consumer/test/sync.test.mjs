// Contract test for the relocated videsign token consumer.
//
// Moved here from the site repository, where it ran under vitest. This port runs
// on `node --test`, which is what this repository already uses, so the consumer
// toolkit needs no additional dependency.
//
// The contract under test is fail-closed: the sync refuses a missing source, a
// missing SHA, a malformed source, an out-of-ceiling fluid token, a wrong hero
// size, and a glass stylesheet without literal backdrop declarations. It records
// provenance for what it writes and produces identical bytes across runs.

import { spawnSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import test from 'node:test';
import assert from 'node:assert/strict';

const HERE = dirname(fileURLToPath(import.meta.url));
const CONSUMER = resolve(HERE, '..');
const SCRIPT = join(CONSUMER, 'sync-videsign-tokens.mjs');
const SOURCE = join(CONSUMER, 'videsign-tokens-source.json');
const GLASS = join(CONSUMER, 'videsign-glass-source.css');
const SHA = 'eb9a67def80c9f0ecbf28a33a31319247ead31b6';

const scratch = mkdtempSync(join(tmpdir(), 'videsign-consumer-'));
test.after(() => rmSync(scratch, { recursive: true, force: true }));

function run(args) {
  const out = join(scratch, 'tokens.css');
  const glassOut = join(scratch, 'glass.css');
  const result = spawnSync(process.execPath, [SCRIPT, '--out', out, '--glass-out', glassOut, ...args], {
    encoding: 'utf8',
    cwd: CONSUMER,
  });
  return { status: result.status, stdout: result.stdout, stderr: result.stderr, out, glassOut };
}

function mutated(fn) {
  const tokens = JSON.parse(readFileSync(SOURCE, 'utf8'));
  fn(tokens);
  const path = join(scratch, 'mutated-tokens.json');
  writeFileSync(path, JSON.stringify(tokens));
  return path;
}

test('a valid pin writes both artifacts and records provenance', () => {
  const r = run(['--source', SOURCE, '--glass', GLASS, '--sha', SHA]);
  assert.equal(r.status, 0, r.stderr);
  const tokens = readFileSync(r.out, 'utf8');
  assert.match(tokens, /GENERATED BY/);
  assert.match(tokens, new RegExp(SHA));
  assert.match(readFileSync(r.glassOut, 'utf8'), /GENERATED BY/);
  assert.match(r.stdout, /36 required tokens present/);
});

test('two runs produce identical bytes', () => {
  const first = run(['--source', SOURCE, '--glass', GLASS, '--sha', SHA]);
  assert.equal(first.status, 0, first.stderr);
  const a = readFileSync(first.out, 'utf8');
  const b = readFileSync(run(['--source', SOURCE, '--glass', GLASS, '--sha', SHA]).out, 'utf8');
  assert.equal(a, b);
});

test('a missing source argument is refused', () => {
  const r = run(['--glass', GLASS, '--sha', SHA]);
  assert.notEqual(r.status, 0);
  assert.match(r.stderr, /--source is required/);
});

test('a missing SHA is refused', () => {
  const r = run(['--source', SOURCE, '--glass', GLASS]);
  assert.notEqual(r.status, 0);
  assert.match(r.stderr, /--sha is required/);
});

test('a source path that does not exist is refused', () => {
  const r = run(['--source', join(scratch, 'absent.json'), '--glass', GLASS, '--sha', SHA]);
  assert.notEqual(r.status, 0);
  assert.match(r.stderr, /source not found/);
});

test('a fluid token over the ceiling is refused', () => {
  const path = mutated(t => {
    t.typography['typography-fluid-display-base'] = 'clamp(2rem, 1.5rem + 2vw, 4rem)';
  });
  const r = run(['--source', path, '--glass', GLASS, '--sha', SHA]);
  assert.notEqual(r.status, 0);
  assert.match(r.stderr, /ceiling/);
});

test('a hero token that is not 5.25rem is refused', () => {
  const path = mutated(t => {
    t.typography['typography-fluid-hero-base'] = 'clamp(2.75rem, 6vw + 0.5rem, 4rem)';
  });
  const r = run(['--source', path, '--glass', GLASS, '--sha', SHA]);
  assert.notEqual(r.status, 0);
  assert.match(r.stderr, /hero token max/);
});

test('an unparseable fluid token is refused', () => {
  const path = mutated(t => {
    t.typography['typography-fluid-body-base'] = 'not-a-clamp';
  });
  const r = run(['--source', path, '--glass', GLASS, '--sha', SHA]);
  assert.notEqual(r.status, 0);
  assert.match(r.stderr, /not a clamp/);
});
