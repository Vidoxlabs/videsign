/** Title-case a kebab-case filename into a human-readable resource name. */
function kebabToTitle(name) {
  return name
    .replace(/\.html$/, '')
    .split('-')
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
    .join(' ');
}

/** Discover all .html files in preview/ and build resource descriptors. */
function discoverPreviewFragments() {
  const previewDir = path.join(__dirname, 'preview');
  const files = fs
    .readdirSync(previewDir)
    .filter((f) => f.endsWith('.html'))
    .sort();

  return files.map((file) => ({
    uri: `file://preview/${file}`,
    name: `${kebabToTitle(file)} Fragment`,
    mimeType: 'text/html',
    description: `Pure HTML fragment for ${kebabToTitle(file).toLowerCase()}.`,
    file,
  }));
}

/** Build the complete resource list: markdown docs + canon + standard + preview fragments. */
function buildResourceList() {
  const mdResources = MD_RESOURCES.map((r) => ({
    uri: `file://${r.file}`,
    name: r.name,
    mimeType: 'text/markdown',
    description: r.description,
    file: r.file,
  }));

  const canonResources = CANON_RESOURCES.map((r) => ({
    uri: `file://${r.file}`,
    name: r.name,
    mimeType: r.mimeType,
    description: r.description,
    file: r.file,
  }));

  const standardResources = STANDARD_RESOURCES
    .filter((r) => fs.existsSync(path.join(__dirname, r.file)))
    .map((r) => ({
      uri: `file://${r.file}`,
      name: r.name,
      mimeType: r.mimeType,
      description: r.description,
      file: r.file,
    }));

  const stylePackResources = STYLE_PACK_RESOURCES
    .filter((r) => fs.existsSync(path.join(__dirname, r.file)))
    .map((r) => ({
      uri: `file://${r.file}`,
      name: r.name,
      mimeType: r.mimeType,
      description: r.description,
      file: r.file,
    }));

   const previewResources = discoverPreviewFragments();

  return [...mdResources, ...canonResources, ...standardResources, ...stylePackResources, ...previewResources];
}

// --- Server setup -------------------------------------------------------

const RESOURCES = buildResourceList();

const server = new Server({
  name: 'videsign-mcp-server',
  version: '1.0.0',
}, {
  capabilities: {
    resources: {},
    tools: {},
  },
});

// --- List Resources -----------------------------------------------------

server.setRequestHandler(ListResourcesRequestSchema, async () => {
  return {
    resources: RESOURCES.map(({ uri, name, mimeType, description }) => ({
      uri,
      name,
      mimeType,
      description,
    })),
  };
});

// --- Read Resource ------------------------------------------------------

server.setRequestHandler(ReadResourceRequestSchema, async (request) => {
  const { uri } = request.params;
  const resource = RESOURCES.find((r) => r.uri === uri);
  if (!resource) {
    throw new Error('Resource not found');
  }

  let filePath;
  let mimeType;

  if (resource.uri.startsWith('file://preview/')) {
    filePath = path.join(__dirname, 'preview', resource.file);
    mimeType = 'text/html';
  } else {
    filePath = path.join(__dirname, resource.file);
    mimeType = resource.mimeType || 'text/markdown';
  }

  const content = fs.readFileSync(filePath, 'utf-8');

  return {
    contents: [{
      uri,
      mimeType,
      text: content,
    }],
  };
});

// --- List Tools ---------------------------------------------------------

