#!/usr/bin/env node

/**
 * generate-dialect-fragment.js: writes preview/persona-dialects.html from lib/dialects.js, so the
 * catalog shows each seat's dialect in the order its replies lead with. test/dialects.test.js
 * fails if the committed fragment drifts. Run `npm run dialects:fragment` after editing the module.
 */

const fs = require('fs');
const path = require('path');
const { PERSONAS, DIALECTS } = require('../lib/dialects');

const FRAGMENT = path.join(__dirname, '..', 'preview', 'persona-dialects.html');

/** Sample copy describes the component, never a product claim. */
const KIND_COPY = {
  summary: ['Summary', 'The short version first.'],
  highlights: ['Highlights', 'Then the passages worth reading, marked on the page.'],
  options: ['Options', 'What you can explore first.'],
  explorations: ['Explorations', 'Then where each option leads.'],
  limits: ['Limits', 'What is not established first.'],
  evidence: ['Evidence', 'Then what the record does show.'],
  alternatives: ['Alternatives', 'The closest matches side by side.'],
  comparison: ['Comparison', 'Then how they differ.'],
  steps: ['Steps', 'The next actions, in order.'],
  progress: ['Progress', 'Then where you are on the path.'],
  sources: ['Sources', 'Every reply closes with its sources.'],
};

const name = (persona) => persona.charAt(0).toUpperCase() + persona.slice(1);

function marker(lit) {
  return PERSONAS.map((persona) =>
    persona === lit
      ? `<span class="w-indicator-mark-base h-indicator-fivebar-base bg-persona-accent-${persona}-base"></span>`
      : `<span class="w-indicator-dot-base h-indicator-fivebar-base opacity-40 bg-persona-accent-${persona}-base"></span>`,
  ).join('');
}

function card(persona) {
  const d = DIALECTS[persona];
  const sections = d.lead.map((kind) => {
    const [label, text] = KIND_COPY[kind];
    return [
      `    <section data-kind="${kind}" class="flex flex-col gap-gap-dense-default">`,
      `      <p class="vi-agent__label font-typography-weight-medium-base text-typography-size-xs-base text-text-content-secondary-base">${label}</p>`,
      `      <p class="font-typography-family-sans-base text-typography-size-sm-base text-text-content-primary-base">${text}</p>`,
      '    </section>',
    ].join('\n');
  });
  return [
    `  <article class="vi-agent w-layout-width-sidebar-base bg-surface-background-secondary-base border border-border-separator-primary-base rounded-layout-radius-standard-base" data-persona="${persona}" aria-labelledby="dialect-${persona}">`,
    '    <div class="vi-agent__motif" aria-hidden="true"></div>',
    '    <div class="flex items-center gap-gap-compact-default">',
    `      <div aria-hidden="true" class="inline-flex gap-gap-dense-default">${marker(persona)}</div>`,
    `      <p id="dialect-${persona}" class="vi-agent__label font-typography-weight-semibold-base text-typography-size-sm-base text-text-content-primary-base">${name(persona)}</p>`,
    '    </div>',
    `    <p class="font-typography-family-sans-base text-typography-size-xs-base text-text-content-secondary-base">${d.role}. ${d.canon.setting}: ${d.canon.mood}.</p>`,
    ...sections,
    '  </article>',
  ].join('\n');
}

function dialectFragment() {
  return [
    '<!--',
    '  Nocturne Museum: Persona dialects (ADR-015)',
    '  Generated by `npm run dialects:fragment` from lib/dialects.js; do not edit by hand.',
    '  One skeleton, five dialects. Each agent surface sets `vi-agent` and `data-persona`; the',
    '  dialect changes tempo, density, label type, a decorative motif and the order a reply leads',
    '  with. Seat names stay in the primary text colour; seat colours mark the five-segment marker',
    '  and the motif only, so no seat colour appears alone. Sections are in DOM order, never',
    '  reordered by CSS, so reading order matches what is shown.',
    '-->',
    '<div class="flex flex-wrap items-start gap-gap-spacious-default">',
    ...PERSONAS.map(card),
    '</div>',
    '',
  ].join('\n');
}

if (require.main === module) {
  fs.writeFileSync(FRAGMENT, dialectFragment());
  process.stdout.write('wrote preview/persona-dialects.html\n');
}

module.exports = { dialectFragment, KIND_COPY };
