#!/usr/bin/env node

/**
 * generate-memory-field-fragment.js: writes preview/memory-field.html and
 * preview/memory-pipeline.html from lib/memory-field.js, so the catalog shows exactly what the
 * primitive renders. test/memory-field.test.js fails if a committed fragment drifts from the
 * renderer. Run `npm run memory-field:fragment` after changing lib/memory-field.js.
 */

const fs = require('fs');
const path = require('path');
const mf = require('../lib/memory-field');

const PREVIEW = path.join(__dirname, '..', 'preview');

function sampleLayout() {
  return mf.layoutMemoryField(mf.sampleMemoryField(), { seed: 5 });
}

function memoryFieldFragment() {
  const layout = sampleLayout();
  const hub = layout.nodes.reduce((best, node) => (node.r > best.r ? node : best), layout.nodes[0]).id;
  const peers = layout.edges.filter((e) => e.source === hub || e.target === hub).map((e) => (e.source === hub ? e.target : e.source));
  const svg = mf.renderMemoryFieldSvg(layout, {
    id: 'preview-mf',
    title: 'Memory field',
    desc: 'A focus on the heaviest memory and its links; the rest of the web is decoration.',
    focus: { nodes: [hub, ...peers] },
  });
  return [
    '<!--',
    '  Nocturne Museum: Memory field (ADR-018)',
    '  Generated by `npm run memory-field:fragment` from lib/memory-field.js; do not edit by hand.',
    '  A deterministic constellation: memory class is the outline shape, mass is the radius, recency',
    '  is the opacity of the mark. The rest web is aria-hidden decoration; lit links carry the',
    '  meaning in their link token, with a dash or arrowhead and a name. Colour and motion come',
    '  from lib/memory-field.css (dist/memory-field.css). Synthetic data, and it says so.',
    '-->',
    '<div class="w-full overflow-hidden rounded-layout-radius-standard-base bg-surface-background-primary-base p-layout-padding-medium-base">',
    `  ${svg.replace('class="vi-mf"', 'class="vi-mf vi-mf--enter"')}`,
    '</div>',
    '',
  ].join('\n');
}

function memoryPipelineFragment() {
  const svg = mf.renderMemoryPipelineSvg(mf.SAMPLE_PIPELINE, {
    id: 'preview-mp',
    title: 'Memory pipeline',
    desc: 'Sources feed the Memorix Postgres authority, which projects to Neo4j, Redis and MinIO; recall lanes read them and hand evidence to ARKSRRA; Forget bumps the deletion epoch so every projection is bypassed and rebuilt.',
  });
  return [
    '<!--',
    '  Nocturne Museum: Memory pipeline (ADR-018 item 7)',
    '  Generated by `npm run memory-field:fragment` from lib/memory-field.js; do not edit by hand.',
    '  Groups, steps (rounded rectangles), stores (cylinders) and labelled flows in the graph line.',
    '  Real components only. Flow pulses are opt-in (data-flow="on") beside a pause control.',
    '-->',
    '<div class="w-full overflow-hidden rounded-layout-radius-standard-base bg-surface-background-primary-base p-layout-padding-medium-base">',
    `  ${svg}`,
    '</div>',
    '',
  ].join('\n');
}

if (require.main === module) {
  fs.writeFileSync(path.join(PREVIEW, 'memory-field.html'), memoryFieldFragment());
  fs.writeFileSync(path.join(PREVIEW, 'memory-pipeline.html'), memoryPipelineFragment());
  process.stdout.write('wrote preview/memory-field.html\nwrote preview/memory-pipeline.html\n');
}

module.exports = { memoryFieldFragment, memoryPipelineFragment, sampleLayout };
