#!/usr/bin/env node

/**
 * generate-stage-fragment.js: writes preview/stage-backdrop.html from lib/stage.js, so the
 * catalog shows exactly what the primitive renders. test/stage.test.js fails if the committed
 * fragment drifts from the renderer. Run `npm run stage:fragment` after changing lib/stage.js.
 */

const fs = require('fs');
const path = require('path');
const { renderStageSvg } = require('../lib/stage');

const FRAGMENT = path.join(__dirname, '..', 'preview', 'stage-backdrop.html');

function stageFragment() {
  return [
    '<!--',
    '  Nocturne Museum: Stage backdrop (ADR-013 item 1)',
    '  Generated by `npm run stage:fragment` from lib/stage.js; do not edit by hand.',
    '  An arc of the five persona lights in canon order (Xylia at the crown) over a stage ring of',
    '  five single-colour segments, with light planes and a centre beam. Every gradient carries',
    '  one signature colour. Decorative and hidden from assistive tech. Shown at hero strength;',
    '  behind reading text a product uses the ambient variant, or a scrim (STAGE_TEXT_SCRIM).',
    '  Colour and motion come from lib/stage.css (dist/stage.css).',
    '-->',
    '<div class="relative w-full aspect-video overflow-hidden rounded-layout-radius-standard-base bg-surface-background-primary-base">',
    `  ${renderStageSvg({ variant: 'hero', idPrefix: 'preview' })}`,
    '</div>',
    '',
  ].join('\n');
}

if (require.main === module) {
  fs.writeFileSync(FRAGMENT, stageFragment());
  process.stdout.write('wrote preview/stage-backdrop.html\n');
}

module.exports = { stageFragment };
