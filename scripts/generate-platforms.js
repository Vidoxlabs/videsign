#!/usr/bin/env node

/**
 * generate-platforms.js: native token outputs for every Vidoxlabs platform (ADR-014).
 *
 * One DESIGN.md, four more outputs, written by `npm run tokens`:
 *   dist/tokens.ts           typed values, CSS variable names and a lookup (web: React, Astro, Next, Vite)
 *   dist/ViTokens.swift      SwiftUI colours, points, seconds, curves (ViApp and other Apple targets)
 *   dist/videsign_tokens.py  read-only mappings for Python and Textual (terminal UIs, CLIs)
 *   dist/tokens.dtcg.json    W3C Design Tokens Community Group format 2025.10 (tools and converters)
 *
 * Deterministic: no timestamps, sorted by DESIGN.md order. Values are converted once, in
 * scripts/lib/token-values.js, so no platform rounds a value differently from another.
 */

const { classify, flattenTokens, camel, upperSnake } = require('./lib/token-values');
const { PERSONAS, resolveDialects } = require('../lib/dialects');

const HEADER = 'GENERATED BY scripts/generate-platforms.js from DESIGN.md. DO NOT EDIT. Run `npm run tokens`.';
const json = (value) => JSON.stringify(value);
const num = (n) => (Number.isInteger(n) ? String(n) : String(Number(n.toFixed(6))));

function groupByCategory(flat) {
  const groups = new Map();
  for (const token of flat) {
    if (!groups.has(token.category)) groups.set(token.category, []);
    groups.get(token.category).push(token);
  }
  return groups;
}

// --- TypeScript ---------------------------------------------------------------

function emitTypeScript(tokens) {
  const flat = flattenTokens(tokens);
  const groups = groupByCategory(flat);
  const lines = [`/* ${HEADER} */`, ''];
  lines.push('/** Raw values exactly as DESIGN.md states them (CSS syntax). */');
  lines.push('export const tokens = {');
  for (const [category, list] of groups) {
    lines.push(`  ${json(category)}: {`);
    for (const t of list) lines.push(`    ${json(t.key)}: ${json(t.raw)},`);
    lines.push('  },');
  }
  lines.push('} as const;', '');
  lines.push('/** `var(--vi-…)` references, for inline-free styling that follows themes.css. */');
  lines.push('export const cssVar = {');
  for (const [category, list] of groups) {
    lines.push(`  ${json(category)}: {`);
    for (const t of list) lines.push(`    ${json(t.key)}: ${json(`var(${t.cssVar})`)},`);
    lines.push('  },');
  }
  lines.push('} as const;', '');
  lines.push('export type TokenCategory = keyof typeof tokens;');
  lines.push('export type TokenKey<C extends TokenCategory> = keyof (typeof tokens)[C];');
  lines.push('export type TokenPath = { [C in TokenCategory]: `${C}.${Extract<TokenKey<C>, string>}` }[TokenCategory];', '');
  lines.push('/** Persona dialects for agent surfaces (ADR-015), resolved: seconds, points, curve points. */');
  lines.push(`export const dialects = ${JSON.stringify(resolveDialects(tokens, classify), null, 2)} as const;`, '');
  lines.push(`export type Persona = ${PERSONAS.map((p) => json(p)).join(' | ')};`, '');
  lines.push('/** Resolve "category.key" to its raw value, or undefined. */');
  lines.push('export function token(path: TokenPath): string {');
  lines.push('  const dot = path.indexOf(".");');
  lines.push('  const category = path.slice(0, dot) as TokenCategory;');
  lines.push('  return (tokens[category] as Record<string, string>)[path.slice(dot + 1)];');
  lines.push('}', '');
  return lines.join('\n');
}

// --- Swift ----------------------------------------------------------------------

function swiftValue(t) {
  const v = t.value;
  switch (v.kind) {
    case 'color':
      return `Color(viHex: 0x${v.hex.slice(1)}${v.alpha === 1 ? '' : `, opacity: ${num(v.alpha)}`})`;
    case 'dimension':
      return `CGFloat(${num(v.points)})`;
    case 'em':
      return `ViEm(${num(v.value)})`;
    case 'number':
      return `Double(${num(v.value)})`;
    case 'fontWeight':
      return `ViFontWeight(${num(v.value)})`;
    case 'duration':
      return `TimeInterval(${num(v.seconds)})`;
    case 'cubicBezier':
      return `ViCurve(${v.points.map(num).join(', ')})`;
    case 'fluid':
      return `ViFluid(min: ${num(v.min.points)}, max: ${num(v.max.points)})`;
    case 'fontFamily':
      return `[${v.families.map(json).join(', ')}]`;
    default:
      return null;
  }
}

/** Persona dialects (ADR-015) as Swift values. */
function swiftDialects(tokens) {
  const resolved = resolveDialects(tokens, classify);
  const strings = (list) => `[${list.map(json).join(', ')}]`;
  const lines = [
    '/// A persona dialect for agent surfaces (ADR-015): tempo, density, label type, motif and the',
    '/// order a reply leads with. Values resolve existing tokens; nothing here is a new colour.',
    'public struct ViDialect: Sendable, Equatable {',
    '    public let persona: String',
    '    public let role: String',
    '    public let duration: TimeInterval',
    '    public let easing: ViCurve',
    '    public let entrance: TimeInterval',
    '    public let gap: CGFloat',
    '    public let padding: CGFloat',
    '    public let labelFamily: [String]',
    '    public let labelTracking: ViEm',
    '    public let leading: Double',
    '    public let tabularNumerals: Bool',
    '    public let motif: String',
    '    public let lead: [String]',
    '}',
    '',
    'public enum ViDialects {',
  ];
  for (const persona of PERSONAS) {
    const d = resolved[persona];
    lines.push(
      `    public static let ${persona} = ViDialect(persona: ${json(persona)}, role: ${json(d.role)}, ` +
        `duration: ${num(d.motion.durationSeconds)}, easing: ViCurve(${d.motion.easing.map(num).join(', ')}), ` +
        `entrance: ${num(d.motion.entranceSeconds)}, gap: ${num(d.density.gapPoints)}, padding: ${num(d.density.paddingPoints)}, ` +
        `labelFamily: ${strings(d.type.labelFamily)}, labelTracking: ViEm(${num(d.type.labelTrackingEm)}), leading: ${num(d.type.leading)}, ` +
        `tabularNumerals: ${d.type.numerals === 'tabular-nums'}, motif: ${json(d.motif)}, lead: ${strings(d.lead)})`,
    );
  }
  lines.push(`    public static let all: [ViDialect] = [${PERSONAS.join(', ')}]`);
  lines.push('    /// The dialect for a seat id, or Violet\'s when the surface has no seat.');
  lines.push('    public static func forPersona(_ id: String?) -> ViDialect { all.first { $0.persona == id } ?? violet }');
  lines.push('}', '');
  return lines;
}

function emitSwift(tokens) {
  const flat = flattenTokens(tokens);
  const groups = groupByCategory(flat);
  const lines = [
    `// ${HEADER}`,
    '// Nocturne Museum tokens for SwiftUI. Points: 1px = 1pt, 1rem = 16pt. Durations in seconds.',
    '// CSS-only values (shadows, gradients, backdrop filters) are listed at the end, not converted.',
    '',
    'import SwiftUI',
    '',
    'public extension Color {',
    '    /// sRGB colour from 0xRRGGBB, as DESIGN.md states it.',
    '    init(viHex hex: UInt32, opacity: Double = 1) {',
    '        self.init(',
    '            .sRGB,',
    '            red: Double((hex >> 16) & 0xFF) / 255,',
    '            green: Double((hex >> 8) & 0xFF) / 255,',
    '            blue: Double(hex & 0xFF) / 255,',
    '            opacity: opacity',
    '        )',
    '    }',
    '}',
    '',
    '/// A multiple of the current font size (CSS `em`), e.g. letter spacing.',
    'public struct ViEm: Sendable, Equatable { public let value: Double; public init(_ value: Double) { self.value = value }',
    '    public func points(fontSize: CGFloat) -> CGFloat { fontSize * CGFloat(value) } }',
    '',
    '/// A CSS font weight (100-900).',
    'public struct ViFontWeight: Sendable, Equatable { public let value: Double; public init(_ value: Double) { self.value = value }',
    '    public var weight: Font.Weight {',
    '        switch value { case ..<150: return .ultraLight; case ..<250: return .thin; case ..<350: return .light',
    '        case ..<450: return .regular; case ..<550: return .medium; case ..<650: return .semibold',
    '        case ..<750: return .bold; case ..<850: return .heavy; default: return .black } } }',
    '',
    '/// A cubic Bézier easing curve, as CSS `cubic-bezier(x1, y1, x2, y2)`.',
    'public struct ViCurve: Sendable, Equatable { public let x1, y1, x2, y2: Double',
    '    public init(_ x1: Double, _ y1: Double, _ x2: Double, _ y2: Double) { self.x1 = x1; self.y1 = y1; self.x2 = x2; self.y2 = y2 }',
    '    public func animation(duration: TimeInterval) -> Animation { .timingCurve(x1, y1, x2, y2, duration: duration) } }',
    '',
    '/// A fluid CSS size (`clamp(min, preferred, max)`): native layouts pick within the bounds, in points.',
    'public struct ViFluid: Sendable, Equatable { public let min, max: CGFloat',
    '    public init(min: CGFloat, max: CGFloat) { self.min = min; self.max = max } }',
    '',
    'public enum ViTokens {',
  ];
  const cssOnly = [];
  for (const [category, list] of groups) {
    const typeName = camel(category).replace(/^./, (c) => c.toUpperCase());
    lines.push(`    public enum ${typeName} {`);
    for (const t of list) {
      const value = swiftValue(t);
      if (value === null) {
        cssOnly.push(`${category}.${t.key}`);
        continue;
      }
      lines.push(`        public static let ${camel(t.key)} = ${value}`);
    }
    lines.push('    }');
  }
  lines.push('}', '');
  lines.push(...swiftDialects(tokens));
  lines.push(`// CSS-only, not converted: ${cssOnly.length ? cssOnly.join(', ') : 'none'}`, '');
  return lines.join('\n');
}

// --- Python -----------------------------------------------------------------------

function pythonValue(t) {
  const v = t.value;
  switch (v.kind) {
    case 'color':
      return v.alpha === 1 ? json(v.hex) : `Rgba(${v.rgb.join(', ')}, ${num(v.alpha)})`;
    case 'dimension':
      return `Px(${num(v.points)})`;
    case 'duration':
      return `Seconds(${num(v.seconds)})`;
    case 'cubicBezier':
      return `(${v.points.map(num).join(', ')})`;
    case 'fluid':
      return `Fluid(${num(v.min.points)}, ${num(v.max.points)})`;
    case 'fontFamily':
      return `(${v.families.map(json).join(', ')},)`;
    case 'em':
    case 'number':
    case 'fontWeight':
      return num(v.value);
    default:
      return json(v.css);
  }
}

function emitPython(tokens) {
  const flat = flattenTokens(tokens);
  const groups = groupByCategory(flat);
  const lines = [
    `"""${HEADER}`,
    '',
    'Nocturne Museum tokens for Python (Textual and other terminal or server UIs).',
    'Colours are "#RRGGBB" strings; translucent colours are Rgba tuples. Sizes are pixels',
    '(1rem = 16px), durations are seconds. Every mapping is read-only.',
    '"""',
    '',
    'from __future__ import annotations',
    '',
    'from types import MappingProxyType',
    'from typing import NamedTuple',
    '',
    '',
    'class Rgba(NamedTuple):',
    '    red: int',
    '    green: int',
    '    blue: int',
    '    alpha: float',
    '',
    '',
    'class Fluid(NamedTuple):',
    '    min: float',
    '    max: float',
    '',
    '',
    'class Px(float):',
    '    """A length in CSS pixels."""',
    '',
    '',
    'class Seconds(float):',
    '    """A duration in seconds."""',
    '',
  ];
  const names = [];
  for (const [category, list] of groups) {
    const name = upperSnake(category);
    names.push(name);
    lines.push('');
    lines.push(`${name} = MappingProxyType({`);
    for (const t of list) lines.push(`    ${json(t.key)}: ${pythonValue(t)},`);
    lines.push('})');
  }
  lines.push('');
  lines.push(`TOKENS = MappingProxyType({${[...groups.keys()].map((c) => `${json(c)}: ${upperSnake(c)}`).join(', ')}})`);
  lines.push('');
  lines.push('CSS_VARS = MappingProxyType({');
  for (const t of flat) lines.push(`    ${json(`${t.category}.${t.key}`)}: ${json(t.cssVar)},`);
  lines.push('})');
  lines.push('');
  lines.push('# Persona dialects for agent surfaces (ADR-015): seconds, pixels, curve points.');
  lines.push('DIALECTS = MappingProxyType({');
  const resolvedDialects = resolveDialects(tokens, classify);
  const py = (value) => {
    if (Array.isArray(value)) return `(${value.map(py).join(', ')}${value.length === 1 ? ',' : ''})`;
    if (value && typeof value === 'object') return `MappingProxyType({${Object.entries(value).map(([k, v]) => `${json(k)}: ${py(v)}`).join(', ')}})`;
    if (typeof value === 'number') return num(value);
    return json(value);
  };
  for (const persona of PERSONAS) lines.push(`    ${json(persona)}: ${py(resolvedDialects[persona])},`);
  lines.push('})');
  lines.push('');
  lines.push('');
  lines.push('def token(path: str):');
  lines.push('    """Resolve "category.key" to its value; raises KeyError when unknown."""');
  lines.push('    category, _, key = path.partition(".")');
  lines.push('    return TOKENS[category][key]');
  lines.push('');
  lines.push('');
  lines.push(`__all__ = ["Rgba", "Fluid", "Px", "Seconds", "TOKENS", "CSS_VARS", "DIALECTS", "token", ${names.map(json).join(', ')}]`);
  lines.push('');
  return lines.join('\n');
}

// --- DTCG 2025.10 -----------------------------------------------------------------------

function dtcgValue(t) {
  const v = t.value;
  switch (v.kind) {
    case 'color':
      return {
        $type: 'color',
        $value: { colorSpace: 'srgb', components: v.rgb.map((c) => Number((c / 255).toFixed(6))), alpha: v.alpha, hex: v.hex },
      };
    case 'dimension':
      return { $type: 'dimension', $value: { value: v.value, unit: v.unit } };
    case 'duration':
      return { $type: 'duration', $value: { value: v.value, unit: v.unit } };
    case 'cubicBezier':
      return { $type: 'cubicBezier', $value: v.points };
    case 'fontFamily':
      return { $type: 'fontFamily', $value: v.families };
    case 'fontWeight':
      return { $type: 'fontWeight', $value: v.value };
    case 'number':
      return { $type: 'number', $value: v.value };
    default:
      return null;
  }
}

function emitDtcg(tokens) {
  const flat = flattenTokens(tokens);
  const doc = {
    $description: `Nocturne Museum design tokens. ${HEADER}`,
  };
  const cssOnly = {};
  for (const t of flat) {
    const entry = dtcgValue(t);
    if (entry === null) {
      cssOnly[`${t.category}.${t.key}`] = t.raw;
      continue;
    }
    doc[t.category] = doc[t.category] || {};
    doc[t.category][t.key] = entry;
  }
  // DTCG dimensions allow only px and rem, and have no type for clamp(), em, shadows as CSS
  // strings, gradients or filters. Those stay CSS and are listed here rather than mistyped.
  doc.$extensions = { 'dev.vidoxlabs.videsign': { cssOnly } };
  return `${JSON.stringify(doc, null, 2)}\n`;
}

/** Every platform output, keyed by its dist/ file name. */
function emitPlatformArtifacts(tokens) {
  return {
    'tokens.ts': emitTypeScript(tokens),
    'ViTokens.swift': emitSwift(tokens),
    'videsign_tokens.py': emitPython(tokens),
    'tokens.dtcg.json': emitDtcg(tokens),
  };
}

module.exports = { emitTypeScript, emitSwift, emitPython, emitDtcg, emitPlatformArtifacts };
